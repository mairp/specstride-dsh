/**
 * The host CLI's code, compiled into the package (fix 2026-11-09).
 *
 * `bin/specstride-host-dsh.mjs` runs `doctor`, `install` and `uninstall`
 * from modules of `src/`, but the package ships only `bin/` and `skills/`
 * (T027) and nothing compiles at install, so those modules are compiled here:
 * every `.ts` reachable by relative import from the entry points goes through
 * `stripTypeScriptTypes(source, { mode: "strip" })`, its relative `./x.ts`
 * specifiers become `./x.mjs`, and it lands under `bin/lib/` at the same
 * relative path. The data files those modules read at load are copied
 * beside them (`packageFile` of `src/package-root.ts` finds them there).
 * Bare imports (`@specstride/host-kit`, `@specstride/contracts`, `node:*`)
 * stay as they are: they resolve from the installed dependencies.
 * Pure of the clock: equal sources give equal output.
 */
import { stripTypeScriptTypes } from "node:module";
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The CLI's entry modules (the `eval` lane is a repository-checkout task: its suites are never shipped). */
export const HOST_CLI_ENTRIES: readonly string[] = ["src/doctor.ts", "src/installer.ts"];
/** Data files the compiled modules read at load, at their checkout paths. */
export const HOST_CLI_DATA: readonly string[] = ["contracts/closed-sets.json"];

const RELATIVE_SPECIFIER = /(\bfrom\s*|\bimport\s*\(\s*)(["'])(\.{1,2}\/[^"']+?)\.ts\2/g;

/** Compile the CLI into `outDir` (default `bin/lib`); returns the written files, relative to the root. */
export function buildHostCli(outDir: string = join(ROOT, "bin", "lib")): string[] {
  if (typeof stripTypeScriptTypes !== "function") throw new Error("build-host-cli: stripTypeScriptTypes is missing — needs Node >= 22.13");
  const srcRoot = join(ROOT, "src");
  const seen = new Set<string>();
  const queue = HOST_CLI_ENTRIES.map((entry) => join(ROOT, entry));
  const written: string[] = [];
  // Each file lands by rename, never by emptying the directory first: a
  // reader running meanwhile (a test importing bin/lib) sees the old file or
  // the new one, never none.
  const place = (target: string, text: string): void => {
    mkdirSync(dirname(target), { recursive: true });
    if (existsSync(target) && readFileSync(target, "utf8") === text) return;
    const temp = `${target}.${process.pid}.tmp`;
    writeFileSync(temp, text);
    renameSync(temp, target);
  };
  while (queue.length > 0) {
    const file = queue.shift() as string;
    if (seen.has(file)) continue;
    seen.add(file);
    if (!file.startsWith(srcRoot + sep)) throw new Error(`build-host-cli: ${relative(ROOT, file)} is outside src/`);
    const source = readFileSync(file, "utf8");
    for (const match of source.matchAll(RELATIVE_SPECIFIER)) queue.push(resolve(dirname(file), `${match[3]}.ts`));
    const out = stripTypeScriptTypes(source, { mode: "strip" }).replace(RELATIVE_SPECIFIER, (_all, lead, quote, spec) => `${lead}${quote}${spec}.mjs${quote}`);
    const target = join(outDir, relative(srcRoot, file)).replace(/\.ts$/, ".mjs");
    place(target, `// Generated by scripts/build-host-cli.ts from ${relative(ROOT, file).split(sep).join("/")} — do not edit.\n${out}`);
    written.push(relative(ROOT, target));
  }
  for (const data of HOST_CLI_DATA) {
    const target = join(outDir, data);
    place(target, readFileSync(join(ROOT, data), "utf8"));
    written.push(relative(ROOT, target));
  }
  // Drop what the build no longer writes.
  const keep = new Set(written.map((file) => join(ROOT, file)));
  for (const entry of readdirSync(outDir, { recursive: true, withFileTypes: true })) {
    const path = join(entry.parentPath, entry.name);
    if (entry.isFile() && !keep.has(path)) rmSync(path);
  }
  return written.sort();
}
