/**
 * T005 — the contract-value generator (research.md R1, data-model §2, gate G-A).
 *
 * Reads the values the halves need at run time from the pinned
 * `@specstride/contracts/records/run-view` and writes
 * `src/shared/generated/contract-values.ts` (values only, frozen). `--check`
 * regenerates in memory and fails naming the first differing value.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  SCHEMA_ID,
  MAJOR,
  LANES,
  ATTENTION_KINDS,
  BUDGET_LEVELS,
  COLLECTION_BOUNDS,
  TEXT_CAP_BYTES,
} from "@specstride/contracts/records/run-view";

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPOSITORY_ROOT = join(PACKAGE_ROOT, "..", "..");
export const GENERATED_PATH = join(PACKAGE_ROOT, "src", "shared", "generated", "contract-values.ts");

type Pin = { version: string; packages: readonly { name: string; sha256: string }[] };

/** The generated file text for a pin record (pure; the tests tamper with the inputs). */
export function renderContractValues(pin: Pin, values: Record<string, unknown> = currentValues()): string {
  const contracts = pin.packages.find((row) => row.name === "@specstride/contracts");
  if (contracts === undefined) throw new Error("core-pin.json holds no @specstride/contracts row");
  const lines = [
    `// GENERATED by scripts/gen-contract-values.ts — do not edit. core ${pin.version}, @specstride/contracts tarball sha256 ${contracts.sha256}`,
    "",
  ];
  for (const [name, value] of Object.entries(values)) {
    const json = JSON.stringify(value, null, 2);
    // Every value is flat (a primitive, a list of text, or a record of scalars): one freeze is a deep freeze.
    const body = typeof value === "object" && value !== null ? `Object.freeze(${json})` : json;
    lines.push(`export const ${name} = ${body} as const;`, "");
  }
  return lines.join("\n");
}

export function currentValues(): Record<string, unknown> {
  return {
    SCHEMA_ID,
    MAJOR_RANGE: { from: MAJOR, to: MAJOR },
    LANES: [...LANES],
    ATTENTION_KINDS: [...ATTENTION_KINDS],
    BUDGET_LEVELS: [...BUDGET_LEVELS],
    BOUNDS: { ...COLLECTION_BOUNDS },
    TEXT_CAP_BYTES,
  };
}

export function readPin(): Pin {
  return JSON.parse(readFileSync(join(REPOSITORY_ROOT, "core-pin.json"), "utf8")) as Pin;
}

/** The first differing line as `{ line, expected, found }`, or null when equal. */
export function firstDifference(expected: string, found: string): { line: number; expected: string; found: string } | null {
  const a = expected.split("\n");
  const b = found.split("\n");
  for (let i = 0; i < Math.max(a.length, b.length); i += 1) {
    if (a[i] !== b[i]) return { line: i + 1, expected: a[i] ?? "<end of file>", found: b[i] ?? "<end of file>" };
  }
  return null;
}

/** The name of the exported value that holds a line, for the failure message. */
function valueNameAt(text: string, line: number): string {
  const lines = text.split("\n");
  for (let i = Math.min(line, lines.length) - 1; i >= 0; i -= 1) {
    const match = /^export const (\w+)/.exec(lines[i] ?? "");
    if (match !== null) return match[1] as string;
  }
  return "header";
}

export function checkContractValues(path: string = GENERATED_PATH): void {
  const expected = renderContractValues(readPin());
  let found = "";
  try {
    found = readFileSync(path, "utf8");
  } catch {
    throw new Error(`${path} is missing — run the build`);
  }
  const difference = firstDifference(expected, found);
  if (difference !== null) {
    throw new Error(
      `contract-values drift at line ${difference.line} (value ${valueNameAt(expected, difference.line)}): ` +
        `pinned ${JSON.stringify(difference.expected)}, file ${JSON.stringify(difference.found)}`,
    );
  }
}

export function writeContractValues(): string {
  const text = renderContractValues(readPin());
  mkdirSync(dirname(GENERATED_PATH), { recursive: true });
  // Rewritten only when it differs: parallel test files read the file while a build runs.
  if (!existsSync(GENERATED_PATH) || readFileSync(GENERATED_PATH, "utf8") !== text) writeFileSync(GENERATED_PATH, text, "utf8");
  return GENERATED_PATH;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.includes("--check")) {
      checkContractValues();
      console.log("contract-values: ok");
    } else {
      console.log(`contract-values: wrote ${writeContractValues()}`);
    }
  } catch (error) {
    console.error(`gen-contract-values: ${(error as Error).message}`);
    process.exit(1);
  }
}
